"""Системный промпт — скрытая инструкция, которая идёт перед каждым диалогом.

Собирается заново на каждый запрос, а не хранится константой, потому что
содержит текущее время. Модель обучена на старых данных и сама не знает,
какое сегодня число.
"""

from datetime import datetime

from app.config import TIMEZONE, TIMEZONE_NAME

# Названия по-русски задаём вручную, а не через locale: настройки локали
# различаются на Windows и в Linux-контейнере, и в образе нужного языка
# может просто не оказаться.
WEEKDAYS = (
    "понедельник", "вторник", "среда", "четверг",
    "пятница", "суббота", "воскресенье",
)

MONTHS = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)

# Базовая часть инструкции — то, что не зависит от времени.
PERSONA = """\
Ты — личный ассистент пользователя, общаешься с ним в Telegram.
Умеешь ставить, показывать и отменять напоминания — разовые и повторяющиеся.
Для этого у тебя есть инструменты. Остальное — обычный разговор.

Правила общения:
- Отвечай по-русски, если пользователь не попросил иного.
- Пиши кратко и по существу: это переписка в мессенджере, а не статья.
- Не используй Markdown-разметку (звёздочки, решётки, обратные кавычки):
  в этом чате она не отображается и превращается в мусорные символы.
- Если вопрос неоднозначный, задай уточняющий вопрос, а не угадывай.
- Не выдумывай факты. Если чего-то не знаешь, так и скажи.

Правила для напоминаний:
- Поставив напоминание, обязательно подтверди словами дату и время, на которое
  оно назначено, — пользователь должен сразу увидеть, если ты понял неверно.
- Если время названо расплывчато («вечером», «на неделе»), уточни, во сколько
  именно, вместо того чтобы выбирать наугад.
- Никогда не выдумывай номера напоминаний: чтобы узнать их, вызови список."""


def format_now(now: datetime) -> str:
    """Человекочитаемая дата вида «понедельник, 27 июля 2026, 17:05»."""
    return (
        f"{WEEKDAYS[now.weekday()]}, {now.day} {MONTHS[now.month - 1]} {now.year}, "
        f"{now:%H:%M}"
    )


def build_system_prompt(now: datetime | None = None) -> str:
    """Собирает полный системный промпт с актуальными датой и временем.

    День недели указываем явно. Это не украшение: на тестах модель, получив
    только дату, ошиблась на два дня при расчёте «в пятницу» — вычисление дня
    недели для неё арифметика, а не языковая задача.
    """
    now = now or datetime.now(TIMEZONE)
    return (
        f"{PERSONA}\n\n"
        f"Текущие дата и время: {format_now(now)} (часовой пояс {TIMEZONE_NAME}).\n"
        f"При любых расчётах дат опирайся только на это значение."
    )
